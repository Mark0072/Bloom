export type DictionaryKey = keyof typeof dictionary.es;

export function t(key: DictionaryKey, language: Language): string {
  return dictionary[language][key] ?? dictionary.es[key];
}

export function tf(key: DictionaryKey, language: Language, vars: Record<string, string | number>): string {
  let text = t(key, language);
  for (const [name, value] of Object.entries(vars)) {
    text = text.replace(`{${name}}`, String(value));
  }
  return text;
}
